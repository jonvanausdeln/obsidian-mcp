async function main() {
  console.log('Creating test note in Obsidian vault...\n');

  // Initialize
  const config = getConfig();
  const logger = initializeLogger({ ...config, logLevel: 'error' as const });
  const retryManager = new RetryManager(
    {
      maxAttempts: config.retryMaxAttempts,
      baseDelay: config.retryBaseDelay,
    },
    logger
  );
  const client = new FileSystemClient(config, logger, retryManager);

  // Create the test note
  const testNotePath = 'MCP Test Note.md';

  try {
    const result = await client.writeFile(testNotePath, testNoteContent, true);

    console.log('✅ Test note created successfully!\n');
    console.log('Details:');
    console.log(`  Path: ${testNotePath}`);
    console.log(`  Full path: ${config.vaultPath}\\${testNotePath}`);
    console.log(`  Created: ${result.created ? 'Yes' : 'No (overwrote existing)'}`);
    console.log(`  Size: ${testNoteContent.length} bytes`);
    console.log('\nYou can now:');
    console.log('  1. Open the note in Obsidian');
    console.log('  2. Use it for testing MCP operations');
    console.log('  3. Run: npm run test:functional');
    console.log('\nNote path for MCP testing: "MCP Test Note.md"');
  } catch (error) {
    console.error('❌ Failed to create test note:', error);
    process.exit(1);
  }
}

main();
